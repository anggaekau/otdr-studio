import { dbToRawPoint, metersToDataSpacing, metersToPropTime } from './constants';
import { recomputeKeyEventsSummary } from './editor';
import { serializeSorDocument } from './writer';
import { computeCrc16CcittFalse } from './crc16';
import { KeyEvent, SorDocument } from './types';

function seededNoise(i: number): number {
  const x = Math.sin(i * 12.9898 + 78.233) * 43758.5453;
  return x - Math.floor(x) - 0.5;
}

export interface SampleSpec {
  id: 'metro-18km' | 'ftth-4km';
}

export function createSampleSorDocument(preset: 'metro-18km' | 'ftth-4km' = 'metro-18km'): SorDocument {
  const isMetro = preset === 'metro-18km';
  const groupIndex = 1.4682;
  const wavelengthNm = isMetro ? 1550 : 1310;
  const pulseWidthNs = isMetro ? 100 : 30;
  const fiberLengthMeters = isMetro ? 18420 : 4260;
  const totalSpanMeters = isMetro ? 22000 : 5500;
  const numPoints = 2200;
  const dx = totalSpanMeters / (numPoints - 1);
  const dataSpacing = metersToDataSpacing(dx, groupIndex);
  const scalingFactor = 1000;
  const attenuationRate = isMetro ? 0.215 : 0.345; // dB/km
  const noiseFloorDb = isMetro ? -44.5 : -41.0;

  const eventSpecs: {
    distM: number;
    kind: 'launch' | 'splice' | 'connector' | 'eof';
    lossDb: number;
    reflDb: number;
    comment: string;
  }[] = isMetro
    ? [
        { distM: 0, kind: 'launch', lossDb: 0.32, reflDb: -41.2, comment: 'Launch Connector ODF-A' },
        { distM: 2850, kind: 'splice', lossDb: 0.08, reflDb: 0, comment: 'Fusion Splice JB-01' },
        { distM: 6420, kind: 'connector', lossDb: 0.45, reflDb: -44.8, comment: 'Patch Panel OTB-02' },
        { distM: 10940, kind: 'splice', lossDb: 0.14, reflDb: 0, comment: 'Fusion Splice JB-03' },
        { distM: 14780, kind: 'splice', lossDb: 0.06, reflDb: 0, comment: 'Fusion Splice JB-04' },
        { distM: fiberLengthMeters, kind: 'eof', lossDb: 0, reflDb: -18.5, comment: 'End of Fiber (ODF-B)' },
      ]
    : [
        { distM: 0, kind: 'launch', lossDb: 0.38, reflDb: -39.5, comment: 'OLT Port 04' },
        { distM: 1120, kind: 'splice', lossDb: 0.11, reflDb: 0, comment: 'Closure FDC-01' },
        { distM: 2450, kind: 'connector', lossDb: 0.52, reflDb: -43.0, comment: 'ODP Splitter Input' },
        { distM: fiberLengthMeters, kind: 'eof', lossDb: 0, reflDb: -21.0, comment: 'ONT Termination' },
      ];

  const rawPoints = new Array<number>(numPoints);
  const startDb = -8.0;

  for (let i = 0; i < numPoints; i++) {
    const distM = i * dx;
    if (distM > fiberLengthMeters + 50) {
      rawPoints[i] = dbToRawPoint(noiseFloorDb + seededNoise(i) * 0.45, scalingFactor);
      continue;
    }

    let db = startDb - (distM / 1000) * attenuationRate;

    for (const ev of eventSpecs) {
      if (distM > ev.distM) {
        db -= ev.lossDb;
      }
      if (ev.kind !== 'splice') {
        const deltaM = distM - ev.distM;
        const pulseSpanM = Math.max(dx * 2, pulseWidthNs * 0.25);
        if (deltaM >= -dx && deltaM <= pulseSpanM * 2.5) {
          const peakHeight =
            ev.kind === 'eof' ? 11.5 : ev.kind === 'launch' ? 7.5 : 4.2;
          const x = deltaM / (pulseSpanM * 0.6);
          db += peakHeight * Math.exp(-x * x);
        }
      }
    }

    if (distM > fiberLengthMeters) {
      const dropFrac = Math.min(1, (distM - fiberLengthMeters) / 50);
      db = db * (1 - dropFrac) + noiseFloorDb * dropFrac;
    }

    db += seededNoise(i) * 0.12;
    rawPoints[i] = dbToRawPoint(db, scalingFactor);
  }

  const events: KeyEvent[] = eventSpecs.map((ev, idx) => {
    const prop = metersToPropTime(ev.distM, groupIndex);
    const code =
      ev.kind === 'eof'
        ? '1E9999'
        : ev.kind === 'splice'
        ? '0F9999'
        : '1F9999';
    return {
      eventNumber: idx + 1,
      propagationTime: prop,
      attenuationCoeffDbKm: attenuationRate,
      eventLossDb: ev.lossDb,
      eventReflectanceDb: ev.reflDb,
      eventCode: code,
      lossMeasurementTechnique: '2P',
      markerLocations: [prop - 400, prop - 150, prop, prop + 250, prop + 500],
      comment: ev.comment,
    };
  });

  const baseDoc: SorDocument = {
    version: 2,
    revisionNumber: 200,
    fileName: isMetro ? 'sample_metro_1550nm.sor' : 'sample_ftth_1310nm.sor',
    genParams: {
      languageCode: 'EN',
      cableId: isMetro ? 'BACKBONE-JKT-BDG-01' : 'FTTH-CLUSTER-MELATI-04',
      fiberId: isMetro ? 'CORE-07 (BLUE)' : 'CORE-02 (ORANGE)',
      fiberType: 652,
      nominalWavelength: wavelengthNm,
      originatingLocation: isMetro ? 'POP Jakarta Pusat' : 'STO Kemang',
      terminatingLocation: isMetro ? 'POP Bekasi Barat' : 'ODP-KMG-042',
      cableCode: isMetro ? 'ADSS-48C-SM' : 'DROP-12C-G657A',
      currentDataFlag: 'BC',
      userOffset: 0,
      userOffsetDistance: 0,
      operator: 'Teknisi Fiber',
      comments: 'Sample trace generated by OTDR .SOR Studio',
    },
    supParams: {
      supplierName: 'OTDR Studio Sim',
      otdrMainframeId: 'FTB-1 Pro',
      otdrMainframeSerial: 'SN-2026-0842',
      opticalModuleId: '730C-SM2',
      opticalModuleSerial: 'MOD-99124',
      softwareVersion: '2.0.0',
      other: 'Telcordia SR-4731 v2.00',
    },
    fxdParams: {
      timestamp: Math.floor(Date.now() / 1000),
      units: 'km',
      actualWavelengthNm: wavelengthNm,
      acquisitionOffset: 0,
      acquisitionOffsetDistance: 0,
      pulseEntries: [
        {
          pulseWidthNs,
          dataSpacing,
          numDataPoints: numPoints,
        },
      ],
      groupIndex,
      backscatterCoeffDb: isMetro ? -79.4 : -77.0,
      numAverages: 1024,
      averagingTimeSec: 15.0,
      acquisitionRange: metersToPropTime(totalSpanMeters, groupIndex),
      acquisitionRangeDistance: Math.round(totalSpanMeters / 1000),
      frontPanelOffset: 0,
      noiseFloorLevelDb: noiseFloorDb,
      noiseFloorScaleFactor: 1000,
      powerOffsetFirstPointDb: 0,
      lossThresholdDb: 0.02,
      reflectanceThresholdDb: -55.0,
      endOfFiberThresholdDb: 3.0,
      traceType: 'ST',
      windowCoordinates: [0, 0, 0, 0],
    },
    keyEvents: {
      events,
      endToEndLossDb: 0,
      endToEndMarkerStart: 0,
      endToEndMarkerEnd: 0,
      opticalReturnLossDb: isMetro ? 34.2 : 31.8,
      orlMarkerStart: 0,
      orlMarkerEnd: metersToPropTime(fiberLengthMeters, groupIndex),
    },
    dataPts: {
      scalingFactor,
      rawPoints,
    },
    extraBlocks: [],
    checksumInfo: {
      present: true,
      stored: 0,
      computed: 0,
      valid: true,
    },
    blockOrder: ['GenParams', 'SupParams', 'FxdParams', 'KeyEvents', 'DataPts', 'Cksum'],
  };

  const finalized = recomputeKeyEventsSummary(baseDoc);
  const bytes = serializeSorDocument(finalized);
  const crc = computeCrc16CcittFalse(bytes, bytes.length - 2);
  finalized.checksumInfo = {
    present: true,
    stored: crc,
    computed: crc,
    valid: true,
  };
  return finalized;
}
